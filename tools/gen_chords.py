import json
d=json.load(open('j6.json'))
notes=d['notes']; names=d['names']; style=d['style']
fix_style={34:'Cinematic/Synthwave',35:'Cinematic/House',38:'New Age/Cinematic',47:'Synthwave/House',57:'House/Techno'}
names=dict(names)
roots=['C','C#','D','D#','E','F','F#','G','G#','A','A#','B']
names['14']=[r+' oct' for r in roots]; names['15']=[r+' 4th' for r in roots]; names['16']=[r+' 5th' for r in roots]
names['24']=[r+'m9/11' for r in roots]
names['47']="Cm7 D#M7 Dm7 Fm7 D#M7 Gm7 Fm7 G#M7 Gm7 A#7 G#M7 C#/C".split()
def clean(n):
    n=n.replace('(n3)o','(no3)').replace('(3)no','(no3)').replace('F#FM7','F#M7')
    return n
lines=["/* SPDX-License-Identifier: MPL-2.0",
" * Copyright (C) 2026 swtdr34mz (CHORDMAN) */",
"/* CHORDMAN's chord sets: the 100 sets of the Roland J-6's Chord Set List (its manual, version 1.02), each twelve",
" * chords, one per pitch class of the key pressed (C .. B), voiced as the J-6 voices them: up to four MIDI notes, lowest",
" * first (0: none). Generated by tools/gen_chords.py from the manual's table. Part of dsp/engine.c. */",
"const chordset_t CHORDSETS[NSETS] = {"]
for k in range(1,101):
    st=fix_style.get(k, style.get(str(k),'')).replace('thwave','Synthwave')
    nm=[clean(x) for x in names[str(k)]]
    ns=notes[str(k)]
    rows=[]
    for c in range(12):
        v=sorted(ns[c])+[0]*(4-len(ns[c]))
        rows.append("{%s}"%",".join(str(x) for x in v))
    lines.append('    {"%s", {%s},\n     {%s}},'%(st.upper(), ",".join(rows), ",".join('"%s"'%x for x in nm)))
lines.append("};")
open('/home/claude/chordman/dsp/chords.c','w').write("\n".join(lines)+"\n")
print(max(len(clean(x)) for v in names.values() for x in v))
