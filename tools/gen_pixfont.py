#!/usr/bin/env python3
"""CHORDMAN's arcade lettering: the Terminus bitmap faces fm1-base carries (ter-u12n, ter-u16b, SIL OFL 1.1) as two
small C tables of the characters the game strip writes. Writes ui_pixfont.c: python3 tools/gen_pixfont.py"""
import sys
from pathlib import Path
HERE = Path(__file__).resolve().parent.parent
CHARS = " !+-./0123456789:ABCDEFGHIJKLMNOPQRSTUVWXYZx%"

def bdf(path):
    lines = Path(path).read_text(errors="replace").splitlines()
    fbb = next(l for l in lines if l.startswith("FONTBOUNDINGBOX")).split()
    cw, ch, fx, fy = map(int, fbb[1:5])
    base = ch + fy
    g, i = {}, 0
    while i < len(lines):
        if lines[i].startswith("ENCODING"):
            code = int(lines[i].split()[1]); j = i
            while not lines[j].startswith("BBX"): j += 1
            bw, bh, bx, by = map(int, lines[j].split()[1:5])
            k = j
            while not lines[k].startswith("BITMAP"): k += 1
            rows = [int(r, 16) for r in lines[k + 1:k + 1 + bh]]
            nb = ((bw + 7) // 8) * 8
            cell = [0] * ch
            top = base - (by + bh)
            for r, bits in enumerate(rows):
                for c in range(bw):
                    if bits >> (nb - 1 - c) & 1:
                        x, y = bx + c, top + r
                        if 0 <= x < cw and 0 <= y < ch:
                            cell[y] |= 1 << (cw - 1 - x)
            g[code] = cell
            i = k + bh
        i += 1
    return cw, ch, g

out = ["/* SPDX-License-Identifier: MPL-2.0", " * Copyright (C) 2026 swtdr34mz (CHORDMAN) */",
       "/* CHORDMAN's arcade lettering, generated by tools/gen_pixfont.py from the Terminus faces fm1-base carries",
       " * (ter-u12n, ter-u16b; Dimitar Zhekov, SIL OFL 1.1): a row a byte, the leftmost pixel the highest bit. Part of",
       " * app.c. */", f'static const char PIX_CHARS[] = "{CHARS}";']
for nm, f in (("PIX12", "ter-u12n.bdf"), ("PIX16", "ter-u16b.bdf")):
    cw, ch, g = bdf(HERE / "fm1-base/assets/fonts" / f)
    out.append(f"#define {nm}_W {cw}\n#define {nm}_H {ch}")
    out.append(f"static const uint8_t {nm}[{len(CHARS)}][{ch}] = {{")
    for c in CHARS:
        out.append("    {" + ", ".join(str(v) for v in g.get(ord(c), [0] * ch)) + "},")
    out.append("};")
(HERE / "ui_pixfont.c").write_text("\n".join(out) + "\n")
print("ui_pixfont.c", len(CHARS), "characters")
